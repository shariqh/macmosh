import AppKit
import MacMoshKit

/// The window's editing keys and Command-W (issue #147), handled by the app itself while the MacMosh window or a
/// sheet on it has the keyboard. Every rule is in `WindowKeys`, where it is tested; this only reads the key press,
/// asks `WindowKeys`, and sends the standard action to the first responder.
///
/// Why not the main menu (way A). Apple's Event Handling Guide, "Handling Key Events" (archived,
/// https://developer.apple.com/library/archive/documentation/Cocoa/Conceptual/EventOverview/HandlingKeyEvents/HandlingKeyEvents.html),
/// says "If no object in the view hierarchy handles the key equivalent, NSApp then sends performKeyEquivalent: to
/// the menus in the menu bar." On GitHub's macOS 15 and 26 runners the app already had a main menu, SwiftUI's,
/// whose Edit menu sends `undo:`, `redo:`, `cut:`, `copy:`, `paste:` and `selectAll:` on Command-Z, Shift-Command-Z,
/// X, C, V and A (run 45541029198). A posted Command-V still left a field empty, and so it did with the same items
/// added by the app (run 45543907012), while the menu bar on screen stayed Finder's. Apple,
/// `NSApplication.ActivationPolicy.accessory`
/// (https://developer.apple.com/documentation/appkit/nsapplication/activationpolicy-swift.enum/accessory): "The
/// application doesn't appear in the Dock and doesn't have a menu bar". So the keys are taken here instead.
///
/// Apple, NSEvent `addLocalMonitorForEvents(matching:handler:)` (macOS 10.6,
/// https://developer.apple.com/documentation/appkit/nsevent/addlocalmonitorforevents(matching:handler:)): "Installs
/// an event monitor that receives copies of events the system posts to this app prior to their dispatch." and "Your
/// handler will not be called for events that are consumed by nested event-tracking loops such as control tracking,
/// menu tracking, or window dragging". So with the menu-bar menu open these keys do nothing new, and another app's
/// keys never come here.
@MainActor final class WindowKeysMonitor {
    static let shared = WindowKeysMonitor()

    private var monitor: Any?
    /// Whether a desk is being made (`WindowActionRunner.making`); Command-W closes nothing then.
    private var making: () -> Bool = { false }

    /// Starts listening, once, when the window first opens; later calls only take the newest `making`. It acts
    /// only while the MacMosh window or a sheet on it is the key window of the active app.
    func start(making: @escaping () -> Bool) {
        self.making = making
        guard monitor == nil else { return }
        // The monitor's handler runs on the main thread, where the app's events are dispatched. The event goes on
        // as before (it is returned) unless `perform` handled its press.
        monitor = NSEvent.addLocalMonitorForEvents(matching: .keyDown) { event in
            let press = Self.press(event)
            return MainActor.assumeIsolated { WindowKeysMonitor.shared.perform(press) } ? nil : event
        }
    }

    /// The key press as `WindowKeys` reads it. Apple, NSEvent `charactersIgnoringModifiers`
    /// (https://developer.apple.com/documentation/appkit/nsevent/charactersignoringmodifiers): "The characters
    /// generated by a key event as if no modifier key (except for Shift) applies."
    private nonisolated static func press(_ event: NSEvent) -> WindowKeys.Press {
        let flags = event.modifierFlags.intersection(.deviceIndependentFlagsMask)
        return WindowKeys.Press(character: event.charactersIgnoringModifiers ?? "",
                                command: flags.contains(.command), shift: flags.contains(.shift),
                                option: flags.contains(.option), control: flags.contains(.control))
    }

    /// Does what the press asks of the window and says true, or says false when it is not the window's.
    private func perform(_ press: WindowKeys.Press) -> Bool {
        // Apple, NSApplication `isActive` (https://developer.apple.com/documentation/appkit/nsapplication/isactive):
        // "A Boolean value indicating whether this is the active app."
        guard NSApp.isActive, let found = keyWindow(), let action = WindowKeys.action(for: press),
              let item = WindowKeys.items.first(where: { $0.action == action }) else { return false }
        if action == .close {
            guard WindowKeys.closes(sheetOpen: found.sheetOpen, making: making()) else { return false }
            // Apple, NSWindow `performClose(_:)` (https://developer.apple.com/documentation/appkit/nswindow/performclose(_:)):
            // "Simulates the user clicking the close button by momentarily highlighting the button and then
            // closing the window."
            found.window.performClose(nil)
            return true
        }
        // Apple, NSApplication `sendAction(_:to:from:)`
        // (https://developer.apple.com/documentation/appkit/nsapplication/sendaction(_:to:from:)): "If aTarget is
        // nil, shared looks for an object that can respond to the message ... It begins with the first responder
        // of the key window." It returns false when nothing took it, and the key then goes on as before.
        return NSApp.sendAction(NSSelectorFromString(item.selector), to: nil, from: nil)
    }

    /// The MacMosh window, when it or a sheet on it has the keyboard, and whether a sheet is open on it.
    private func keyWindow() -> (window: NSWindow, sheetOpen: Bool)? {
        guard let key = NSApp.keyWindow else { return nil }
        if key.title == WindowWords.title { return (key, key.attachedSheet != nil) }
        if let parent = key.sheetParent, parent.title == WindowWords.title { return (parent, true) }
        return nil
    }

    // MARK: the log

    /// What the main menu holds: nil when there is none. Apple, NSApplication `mainMenu`
    /// (https://developer.apple.com/documentation/appkit/nsapplication/mainmenu): "The app's main menu bar."
    /// Each key is followed by its item's action: `cmd-v>paste:`.
    static func summary(_ menu: NSMenu?) -> [WindowKeys.MenuSummary]? {
        guard let menu else { return nil }
        return menu.items.map { top in
            WindowKeys.MenuSummary(title: top.submenu?.title ?? top.title,
                                   keys: (top.submenu?.items ?? []).filter { !$0.keyEquivalent.isEmpty }.map { item in
                                       keyName(item) + (item.action.map { ">" + NSStringFromSelector($0) } ?? "")
                                   })
        }
    }

    /// An item's key as `WindowKeys.keyName` writes it. A capital letter as the key means Shift is part of it.
    private static func keyName(_ item: NSMenuItem) -> String {
        let mask = item.keyEquivalentModifierMask
        let key = item.keyEquivalent
        let capital = key.count == 1 && key != key.lowercased()
        return WindowKeys.keyName(key, command: mask.contains(.command), shift: mask.contains(.shift) || capital,
                                  option: mask.contains(.option), control: mask.contains(.control))
    }

    #if DEBUG
    /// Debug builds: one log line with what the main menu holds now, and another a moment later, once the app is
    /// active. CI reads them (issue #147).
    static func logMainMenu() {
        MenuLog.write(MenuLog.mainMenu(summary(NSApp.mainMenu)))
        Task { @MainActor in
            try? await Task.sleep(for: .seconds(2))
            MenuLog.write(MenuLog.mainMenu(summary(NSApp.mainMenu)))
        }
    }
    #endif
}
